/**
 * BEAN Intelligence — vendor materialization for CODE GIFTZ frontend
 * generation (supply-chain layer, Phase 7).
 *
 * Generated projects must work OFFLINE inside the CSP-restricted preview
 * iframe (default-src 'none'; no remote fetches). When a plan uses GSAP or a
 * Vanta effect, the engine therefore attaches the pinned, minified UMD builds
 * read from BEAN's own installed node_modules as ordinary project files:
 *   vendor/gsap.min.js, vendor/ScrollTrigger.min.js,
 *   vendor/three.min.js, vendor/vanta.<effect>.min.js
 * The preview route already inlines project .js files referenced with
 * relative src tags, so the vendored runtime works with zero remote requests.
 *
 * Sources are read from disk once per process and cached (pinned versions,
 * immutable content). A missing vendor file fails the plan LOUDLY instead of
 * generating a project that references a script that will never load.
 */
import fs from 'fs'
import path from 'path'
import { PINNED_DEPENDENCIES } from './catalog'

export interface VendorFileSpec {
  path: string
  /** node_modules-relative source path. */
  source: string
  packageName: string
}

export const GSAP_VENDOR: VendorFileSpec[] = [
  { path: 'vendor/gsap.min.js', source: 'gsap/dist/gsap.min.js', packageName: 'gsap' },
  { path: 'vendor/ScrollTrigger.min.js', source: 'gsap/dist/ScrollTrigger.min.js', packageName: 'gsap' },
]

export function vantaVendor(effectId: string): VendorFileSpec[] {
  return [
    { path: 'vendor/three.min.js', source: 'three/build/three.min.js', packageName: 'three' },
    { path: `vendor/vanta.${effectId}.min.js`, source: `vanta/dist/vanta.${effectId}.min.js`, packageName: 'vanta' },
  ]
}

const cache = new Map<string, string>()

/** Resolve a node_modules path that works in dev, tests AND the standalone
 *  production build (outputFileTracingIncludes copies the same relative
 *  paths into .next/standalone). */
function nodeModulesPath(relative: string): string {
  return path.join(process.cwd(), 'node_modules', relative)
}

function readVendor(spec: VendorFileSpec): string {
  const cached = cache.get(spec.source)
  if (cached !== undefined) return cached
  const full = nodeModulesPath(spec.source)
  if (!fs.existsSync(full)) {
    throw new Error(
      `Frontend toolkit: vendored runtime missing (${spec.packageName} → ${spec.source}). ` +
        'The plan references a library whose pinned build is not installed — generation stopped rather than emitting a broken project.',
    )
  }
  const content = fs.readFileSync(full, 'utf8')
  cache.set(spec.source, content)
  return content
}

/**
 * Materialize the vendor files a plan needs. `gsap` attaches the GSAP core;
 * `scrollTrigger` adds the ScrollTrigger plugin build; effects add three.js +
 * the per-effect Vanta bundle. Throws (honest failure) if a build is missing.
 */
export function vendorProjectFiles(opts: { gsap?: boolean; scrollTrigger?: boolean; vantaEffects?: string[] }): Array<{ path: string; content: string }> {
  const files: Array<{ path: string; content: string }> = []
  if (opts.gsap) {
    for (const spec of GSAP_VENDOR.slice(0, opts.scrollTrigger ? 2 : 1)) {
      files.push({ path: spec.path, content: readVendor(spec) })
    }
  }
  for (const effectId of opts.vantaEffects ?? []) {
    for (const spec of vantaVendor(effectId)) {
      files.push({ path: spec.path, content: readVendor(spec) })
    }
  }
  return files
}

/**
 * package.json for React-target generated projects — the SAME tested versions
 * BEAN runs (exact pins; the user's project installs them, BEAN never
 * auto-installs anything into the user's environment).
 */
export function reactPackageJson(deps: string[]): string {
  const versions = PINNED_DEPENDENCIES
  const entries: Record<string, string> = {
    react: '^19.0.0',
    'react-dom': '^19.0.0',
  }
  for (const name of deps) {
    const pin = versions[name]
    if (!pin) throw new Error(`Frontend toolkit: no pinned version recorded for dependency '${name}'.`)
    entries[name] = pin.version
  }
  return `${JSON.stringify(
    {
      name: 'giftz-frontend-app',
      private: true,
      version: '0.1.0',
      description: 'Generated by CODE GIFTZ (BEAN Intelligence) — Frontend Intelligence Toolkit.',
      dependencies: entries,
    },
    null,
    2,
  )}\n`
}

/**
 * NOTICES.md emitted into every generated project that carries third-party
 * code (vendored runtimes and/or React Bits catalogue components).
 */
export function buildNoticesMarkdown(opts: { reactBitsComponents: string[]; vendored: string[] }): string {
  const lines: string[] = [
    '# Third-party notices',
    '',
    'This project was generated by CODE GIFTZ (BEAN Intelligence) and includes the following third-party software:',
    '',
  ]
  if (opts.vendored.length > 0) {
    lines.push('## Vendored runtime libraries (vendor/)', '')
    if (opts.vendored.some((v) => v.startsWith('vendor/gsap'))) {
      lines.push(
        `- GSAP ${PINNED_DEPENDENCIES.gsap.version} — Standard "No Charge" GSAP License (free, including commercial use): https://gsap.com/standard-license — Copyright Webflow / GreenSock. Notices must be preserved.`,
      )
    }
    if (opts.vendored.some((v) => v.startsWith('vendor/three'))) {
      lines.push(
        `- three.js ${PINNED_DEPENDENCIES.three.version} — MIT License — Copyright © 2010-2021 three.js authors: https://github.com/mrdoob/three.js/blob/r134/LICENSE`,
      )
    }
    if (opts.vendored.some((v) => v.startsWith('vendor/vanta'))) {
      lines.push(
        `- Vanta ${PINNED_DEPENDENCIES.vanta.version} — MIT License — Copyright 2020 Teng Bao: https://github.com/tengbao/vanta`,
      )
    }
    lines.push('')
  }
  if (opts.reactBitsComponents.length > 0) {
    lines.push(
      '## React Bits components (components/kit/)',
      '',
      `Components: ${opts.reactBitsComponents.join(', ')}`,
      '',
      `React Bits by David Haz — MIT + Commons Clause License Condition v1.0.`,
      'Permitted for use as part of an application, website or product (this project);',
      'the components themselves may not be sold or redistributed standalone.',
      `Source: https://github.com/DavidHDev/react-bits — attribution preserved in each component file.`,
      '',
    )
  }
  lines.push('Generated ' + new Date().toISOString().slice(0, 10) + ' — keep this file when redistributing the project.')
  return lines.join('\n') + '\n'
}
