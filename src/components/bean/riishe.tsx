function useCopy(): [boolean, (text: string) => void] {
  const [copied, setCopied] = useState(false)
  const copy = useCallback((text: string) => {
    const done = () => {
      setCopied(true)
      setTimeout(() => setCopied(false), 1600)
    }
    if (navigator.clipboard?.writeText) {
      navigator.clipboard.writeText(text).then(done).catch(done)
    } else {
      const ta = document.createElement('textarea')
      ta.value = text
      document.body.appendChild(ta)
      ta.select()
      document.execCommand('copy')
      document.body.removeChild(ta)
      done()
    }
  }, [])
  return [copied, copy]
}

/** Code block with real syntax highlighting and a working copy button. */
function CodeBlock({ code, lang }: { code: string; lang?: string }) {
  const [copied, copy] = useCopy()
  return (
    <div className="group/code relative my-2 overflow-hidden rounded-[10px] border border-[rgba(212,175,55,0.18)]">
      <div className="flex items-center justify-between bg-black/60 px-3 py-1">
        <span className="text-[10px] uppercase tracking-wider text-white/35">{lang || 'code'}</span>
        <button
          onClick={() => copy(code)}
          className="inline-flex items-center gap-1 rounded px-1.5 py-0.5 text-[10px] text-white/45 transition-colors hover:bg-white/10 hover:text-white/80"
          aria-label="Copy code"
        >
          {copied ? <Check className="h-3 w-3 text-emerald-400" /> : <Copy className="h-3 w-3" />}
          {copied ? 'Copied' : 'Copy'}
        </button>
      </div>
      <SyntaxHighlighter
        language={lang || 'text'}
        style={vscDarkPlus}
        customStyle={{ margin: 0, background: '#0c0c0f', fontSize: '12.5px', padding: '12px 14px' }}
        wrapLongLines={false}
      >
        {code}
      </SyntaxHighlighter>
    </div>
  )
}

function formatBytes(n: number): string {
  if (n < 1024) return `${n} B`
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`
  return `${(n / (1024 * 1024)).toFixed(1)} MB`
}

export function Riishe() {
  const [conversations, setConversations] = useState<Conv[]>([])
  const [activeId, setActiveId] = useState<string | null>(null)
  const [messages, setMessages] = useState<Msg[]>([])
  const [input, setInput] = useState('')
  const [streaming, setStreaming] = useState(false)
  const [researching, setResearching] = useState(false)
  const [runningTool, setRunningTool] = useState<string | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [files, setFiles] = useState<FileMeta[]>([])
  const [uploadingCount, setUploadingCount] = useState(0)
  const [dragOver, setDragOver] = useState(false)
  const endRef = useRef<HTMLDivElement>(null)
  const scrollRef = useRef<HTMLDivElement>(null)
  const nearBottomRef = useRef(true)
  const streamedRef = useRef('')
  const abortRef = useRef<AbortController | null>(null)
  const fileInputRef = useRef<HTMLInputElement>(null)

  const MAX_FILES = 3

  const loadConversations = useCallback(async () => {
    try {
      const d = await beanFetch<{ conversations: Conv[] }>('/api/riishe/chat')
      setConversations(d.conversations)
    } catch { /* non-fatal */ }
  }, [])

  useEffect(() => { void loadConversations() }, [loadConversations])

  // Auto-scroll ONLY while the reader is already at (or near) the bottom.
  // Without this guard every streamed delta / expanded Sources section yanks
  // the viewport back down while the user reads an earlier answer (measured
  // overlap/jump defect class in the work order).
  useEffect(() => {
    const el = scrollRef.current
    if (!el) return
    const onScroll = () => {
      nearBottomRef.current = el.scrollHeight - el.scrollTop - el.clientHeight < 140
    }
    el.addEventListener('scroll', onScroll, { passive: true })
    return () => el.removeEventListener('scroll', onScroll)
  }, [])

  useEffect(() => {
    if (!nearBottomRef.current) return
    endRef.current?.scrollIntoView({ behavior: 'smooth', block: 'end' })
  }, [messages, streaming, researching, runningTool])

  async function openConversation(id: string) {
    setActiveId(id)
    setError(null)
    setFiles([])
    nearBottomRef.current = true
    try {
      const d = await beanFetch<{
        conversation: { messages: Array<{ id: string; role: string; content: string; metadata?: MsgMeta | null }> }
      }>(`/api/riishe/conversations/${id}`)
      setMessages(
        d.conversation.messages.map((m) => ({
          id: m.id,
          serverId: m.id,
          role: m.role as 'user' | 'assistant',
          content: m.content,
          meta: m.metadata ?? undefined,
        })),
      )
    } catch (e) {
      setError((e as Error).message)
    }
  }

  async function deleteConversation(id: string) {
    try {
      await beanFetch(`/api/riishe/conversations/${id}`, { method: 'DELETE' })
      if (activeId === id) { setActiveId(null); setMessages([]) }
      void loadConversations()
    } catch (e) {
      setError((e as Error).message)
    }
  }

  function newConversation() {
    setActiveId(null)
    setMessages([])
    setError(null)
    setFiles([])
  }

  async function uploadOne(file: File) {
    const form = new FormData()
    form.append('file', file)
    const res = await fetch('/api/riishe/documents', { method: 'POST', body: form })
    const data = await res.json().catch(() => ({}))
    if (res.status === 401) window.dispatchEvent(new Event('bean:unauthorized'))
    if (!res.ok && res.status !== 415) {
      throw new Error(data?.error?.message ?? `Upload failed (${res.status})`)
    }
    if (res.status === 415 && !data?.document) {
      // Unsafe or rejected outright — surface the server's actionable reason.
      throw new Error(data?.error?.message ?? 'This file cannot be processed.')
    }
    setFiles((prev) => [...prev, data.document as FileMeta].slice(0, MAX_FILES))
    if (data.document?.status === 'unsupported') {
      setError(data.document.note ?? 'This file type cannot be analyzed yet — it stays attached but adds nothing to the answer.')
    }
  }

  async function uploadFiles(list: FileList | File[]) {
    const incoming = Array.from(list)
    if (incoming.length === 0 || uploadingCount > 0) return
    const room = MAX_FILES - files.length
    if (room <= 0) {
      setError(`Up to ${MAX_FILES} attachments per message.`)
      return
    }
    setError(null)
    setUploadingCount(incoming.length)
    const batch = incoming.slice(0, room)
    let failures = 0
    for (const f of batch) {
      try {
        await uploadOne(f)
      } catch (e) {
        failures += 1
        setError((e as Error).message)
      } finally {
        setUploadingCount((c) => Math.max(0, c - 1))
      }
    }
    if (failures > 0 && batch.length > failures) {
      setError('Some files were rejected — the message explains each failure.')
    }
  }

  function stopGeneration() {
    abortRef.current?.abort()
  }

  /** Regenerate the response to a SPECIFIC user turn (consistent actions on
   *  every assistant message). For the trailing exchange this is the classic
   *  retry; for earlier messages the server removes that exchange and
   *  everything after it, then answers the same user turn again. */
  function regenerateFrom(asstMsg: Msg) {
    if (streaming) return
    const idx = messages.findIndex((m) => m.id === asstMsg.id)
    if (idx < 0) return
    let userIdx = -1
    for (let i = idx - 1; i >= 0; i -= 1) {
      if (messages[i].role === 'user') { userIdx = i; break }
    }
    if (userIdx < 0) return
    const userContent = messages[userIdx].content
    const isTrailing = idx === messages.length - 1
    // Without a persisted id a mid-conversation regenerate cannot truncate
    // server-side history — refuse rather than silently duplicating the turn.
    if (!isTrailing && !asstMsg.serverId) return
    // Drop everything from the user turn onward (locally; the server mirrors
    // this for earlier messages so history stays an honest sequence).
    setMessages(messages.slice(0, userIdx))
    setTimeout(() => void send(userContent, { retry: isTrailing && !asstMsg.serverId, retryFromId: isTrailing ? undefined : asstMsg.serverId }), 0)
  }

  async function send(overrideMessage?: string, opts?: { retry?: boolean; retryFromId?: string }) {
    const message = (overrideMessage ?? input).trim()
    if (!message || streaming) return
    if (overrideMessage === undefined) setInput('')
    setError(null)
    setStreaming(true)
    setResearching(false)
    setRunningTool(null)
    nearBottomRef.current = true // a sent message always scrolls into view
    streamedRef.current = ''

    const userMsg: Msg = { id: `u-${Date.now()}`, role: 'user', content: message }
    const asstId = `a-${Date.now()}`
    setMessages((prev) => [...prev, userMsg, { id: asstId, role: 'assistant', content: '', pending: true }])

    const controller = new AbortController()
    abortRef.current = controller
    const attachable = files.filter((f) => f.status === 'ready')

    try {
      const res = await fetch(`/api/riishe/chat?stream=1${activeId ? `&conversationId=${activeId}` : ''}`, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({
          message,
          conversationId: activeId ?? undefined,
          documentIds: attachable.length > 0 ? attachable.map((d) => d.id) : undefined,
          retry: opts?.retry ?? false,
          ...(opts?.retryFromId ? { retryFromMessageId: opts.retryFromId } : {}),
        }),
        signal: controller.signal,
      })
      if (!res.ok || !res.body) {
        // Keep the global identity in sync: a 401 here means the session is
        // gone server-side; drop the signed-in shell immediately.
        if (res.status === 401) window.dispatchEvent(new Event('bean:unauthorized'))
        const data = await res.json().catch(() => ({}))
        throw new Error(data?.error?.message ?? `Request failed (${res.status})`)
      }
      const reader = res.body.getReader()
      const decoder = new TextDecoder()
      let buffer = ''
      let convId: string | null = activeId
      let failed = false

      while (true) {
        const { done, value } = await reader.read()
        if (done) break
        buffer += decoder.decode(value, { stream: true })
        const lines = buffer.split('\n')
        buffer = lines.pop() ?? ''
        for (const line of lines) {
          if (!line.startsWith('data: ')) continue
          let evt: {
            delta?: string
            reset?: boolean
            done?: boolean
            error?: string
            code?: string
            conversationId?: string
            messageId?: string
            partial?: boolean
            stage?: 'researching' | 'tools' | 'solving' | 'verifying'
            tool?: { name: string; status: 'started' | 'done' | 'failed' }
            meta?: MsgMeta
          }
          try { evt = JSON.parse(line.slice(6)) } catch { continue }
          if (evt.conversationId) convId = evt.conversationId
          if (evt.stage === 'researching') setResearching(true)
          if (evt.stage === 'tools') { setResearching(false); setRunningTool('working') }
          if (evt.stage === 'solving' || evt.stage === 'verifying') { setResearching(false); setRunningTool(null) }
          if (evt.tool) {
            if (evt.tool.status === 'started') setRunningTool(evt.tool.name)
            else setRunningTool(null)
          }
          if (evt.reset) {
            // Reset protocol: a verification rewrite replaced the streamed
            // draft — clear it so the final answer REPLACES, never appends.
            streamedRef.current = ''
            setMessages((prev) =>
              prev.map((m) => (m.id === asstId ? { ...m, content: '', pending: true } : m)),
            )
          }
          if (evt.error) { failed = true; setError(evt.error) }
          if (evt.delta) {
            streamedRef.current += evt.delta
            setMessages((prev) =>
              prev.map((m) => (m.id === asstId ? { ...m, content: streamedRef.current, pending: false } : m)),
            )
          }
          if (evt.done) {
            setResearching(false)
            setRunningTool(null)
            if (convId && !activeId) setActiveId(convId)
            if (evt.messageId) {
              setMessages((prev) => prev.map((m) => (m.id === asstId ? { ...m, serverId: evt.messageId } : m)))
            }
            if (evt.meta) {
              setMessages((prev) => prev.map((m) => (m.id === asstId ? { ...m, meta: evt.meta } : m)))
            }
          }
        }
      }
      // If nothing streamed (failed, or the server reported an empty partial),
      // drop the empty assistant bubble — the error banner already explains
      // what happened, and a perpetual "thinking" indicator would be a lie.
      if (streamedRef.current === '') {
        setMessages((prev) => prev.filter((m) => m.id !== asstId))
        // Server-side failure (e.g. upstream rate limit) reported over SSE:
        // the question goes back into the composer so a retry needs no
        // retyping. (Nothing was answered — no partial content is lost.)
        if (failed) restoreQuestionForRetry(message)
      } else if (failed) {
        setMessages((prev) => prev.map((m) => (m.id === asstId ? { ...m, partial: true, pending: false } : m)))
      }
      void loadConversations()
    } catch (e) {
      if ((e as Error).name === 'AbortError') {
        // User pressed stop: keep what arrived and label it honestly.
        if (streamedRef.current !== '') {
          setMessages((prev) => prev.map((m) => (m.id === asstId ? { ...m, partial: true, pending: false } : m)))
        } else {
          setMessages((prev) => prev.filter((m) => m.id !== asstId))
        }
      } else {
        setError((e as Error).message)
        setMessages((prev) => prev.filter((m) => m.id !== asstId || m.content.length > 0))
        restoreQuestionForRetry(message)
      }
    } finally {
      setStreaming(false)
      setResearching(false)
      setRunningTool(null)
      abortRef.current = null
      setMessages((prev) => prev.map((m) => ({ ...m, pending: false })))
    }
  }

  /** After a failed turn, put the question back into the composer so the
   *  user can retry with Enter — no retyping. Never clobbers text the user
   *  has already started typing. */
  function restoreQuestionForRetry(question: string) {
    setInput((current) => (current.trim().length === 0 ? question : current))
  }

  const citationComponents = () => ({
    a: ({ href, children }: { href?: string; children?: React.ReactNode }) => {
      if (href?.startsWith('#bean-src-')) {
        return (
          <a
            href={href}
            className="mx-0.5 rounded bg-[rgba(212,175,55,0.14)] px-1 text-[11px] text-[#e6c25a] no-underline hover:bg-[rgba(212,175,55,0.28)] hover:text-[#f0c75e]"
            title="Show source"
          >
            {children}
          </a>
        )
      }
      return (
        <a href={href} target="_blank" rel="noopener noreferrer" className="break-words text-[#f0c75e] underline decoration-[rgba(212,175,55,0.4)] hover:decoration-[#f0c75e]">
          {children}
        </a>
      )
    },
    pre: ({ children }: { children?: React.ReactNode }) => {
      // React-markdown nests <code> inside <pre>; extract for highlighting.
      const child = Array.isArray(children) ? children[0] : children
      const props = (child as { props?: { className?: string; children?: ReactNode } })?.props
      const lang = props?.className?.replace(/language-/, '') || undefined
      const code = String(props?.children ?? '').replace(/\n$/, '')
      if (code === '') return <pre>{children}</pre>
      return <CodeBlock code={code} lang={lang} />
    },
  })
  const renderers = citationComponents()

  return (
    <div
      className="flex h-[calc(100vh-3.5rem-2rem)] min-h-[540px] lg:h-[calc(100vh-3.5rem-1.5rem)]"
      onDragOver={(e) => {
        e.preventDefault()
        setDragOver(true)
      }}
      onDragLeave={(e) => {
        if (e.currentTarget === e.target) setDragOver(false)
      }}
      onDrop={(e) => {
        e.preventDefault()
        setDragOver(false)
        if (e.dataTransfer?.files?.length) void uploadFiles(e.dataTransfer.files)
      }}
    >
      {/* Conversation rail */}
      <aside className="hidden w-60 shrink-0 flex-col border-r border-[rgba(212,175,55,0.1)] md:flex">
        <div className="p-3">
          <Button onClick={newConversation} className="w-full justify-start bg-[rgba(212,175,55,0.12)] text-[#f0c75e] hover:bg-[rgba(212,175,55,0.2)]" variant="outline">
            <Plus className="mr-1.5 h-4 w-4" /> New conversation
          </Button>
        </div>
        <ScrollArea className="flex-1 px-2 pb-3">
          {conversations.length === 0 ? (
            <p className="px-2 py-6 text-center text-xs text-white/30">No conversations yet</p>
          ) : (
            conversations.map((c) => (
              <div
                key={c.id}
                className={cn(
                  'group mb-0.5 flex cursor-pointer items-center justify-between rounded-lg px-3 py-2 text-[13px] transition-colors',
                  activeId === c.id ? 'bg-[rgba(212,175,55,0.1)] text-[#f0c75e]' : 'text-white/60 hover:bg-white/5',
                )}
                onClick={() => openConversation(c.id)}
              >
                <div className="min-w-0">
                  <div className="truncate">{c.title}</div>
                  <div className="text-[10px] text-white/30">{c.messages} msgs · {timeAgo(c.updatedAt)}</div>
                </div>
                <button
                  className="ml-2 hidden text-white/30 hover:text-red-400 group-hover:block"
                  onClick={(e) => { e.stopPropagation(); void deleteConversation(c.id) }}
                  aria-label={`Delete ${c.title}`}
                >
                  <Trash2 className="h-3.5 w-3.5" />
                </button>
              </div>
            ))
          )}
        </ScrollArea>
      </aside>

      {/* Chat column */}
      <div className="flex min-w-0 flex-1 flex-col">
        <div className="flex items-center gap-2 border-b border-[rgba(212,175,55,0.1)] px-5 py-3">
          <MessageSquareText className="h-4 w-4 text-[#d4af37]" />
          <div className="text-sm font-semibold tracking-wide">RIISHE</div>
          <span className="text-xs text-white/35">Conversational AI · live sources when needed</span>
        </div>

        <div ref={scrollRef} className="bean-scroll relative flex-1 overflow-y-auto px-5 py-4">
          {messages.length === 0 ? (
            <EmptyState
              icon={<MessageSquareText className="h-10 w-10" />}
              title="Start a conversation"
              hint="Ask questions, request derivations, code help or research on current topics. RIISHE searches live sources when a question needs them and verifies its arithmetic before answering."
            />
          ) : null}
          {messages.length > 0 ? (
            <div className="mx-auto max-w-3xl space-y-4">
              {messages.map((m) => (
                <div key={m.id} className={cn('flex', m.role === 'user' ? 'justify-end' : 'justify-start')}>
                  <div
                    className={cn(
                      // min-w-0 + break-words: long URLs / source names wrap
                      // inside the bubble instead of overflowing it.
                      'max-w-[85%] rounded-2xl px-4 py-3',
                      m.role === 'user'
                        ? 'bg-[rgba(212,175,55,0.14)] text-white/90'
                        : 'bean-glass break-words text-white/85',
                    )}
                  >
                    {m.role === 'user' ? (
                      <p className="whitespace-pre-wrap text-[14.5px] leading-relaxed">{m.content}</p>
                    ) : m.content || m.pending ? (
                      <AssistantBubble
                        msg={m}
                        onRegenerate={() => regenerateFrom(m)}
                        streaming={streaming}
                        renderers={renderers}
                        researching={researching}
                        runningTool={runningTool}
                      />
                    ) : null}
                  </div>
                </div>
              ))}
              <div ref={endRef} />
            </div>
          ) : null}
        </div>

        {error ? (
          <div className="mx-5 mb-2 rounded-md border border-red-500/30 bg-red-500/10 px-3 py-2 text-xs text-red-300">{error}</div>
        ) : null}

        {/* Attachments */}
        {files.length > 0 || uploadingCount > 0 ? (
          <div className="mx-auto flex w-full max-w-3xl flex-wrap gap-2 px-4 pb-1">
            {files.map((d) => (
              <span
                key={d.id}
                className={cn(
                  'inline-flex items-center gap-1.5 rounded-full border px-2.5 py-1 text-[11px]',
                  d.status === 'ready'
                    ? 'border-[rgba(212,175,55,0.3)] bg-[rgba(212,175,55,0.08)] text-[#f0c75e]'
                    : 'border-amber-500/40 bg-amber-500/10 text-amber-300',
                )}
                title={d.note ?? (d.status === 'ready' ? 'Ready — content will be analyzed with the message' : '')}
              >
                <FileText className="h-3 w-3" />
                {d.name}
                <span className="text-white/35">{formatBytes(d.size)}</span>
                {d.status === 'ready' && typeof d.characters === 'number' ? (
                  <span className="text-white/35">· {d.characters.toLocaleString()} chars</span>
                ) : null}
                {d.truncated ? <span className="text-amber-300">· truncated</span> : null}
                {d.status === 'unsupported' ? <span>· can't analyze{d.note ? `: ${d.note.slice(0, 60)}` : ''}</span> : null}
                <button
                  onClick={() => setFiles((prev) => prev.filter((x) => x.id !== d.id))}
                  className="ml-0.5 text-white/40 hover:text-white/80"
                  aria-label={`Remove ${d.name}`}
                >
                  <X className="h-3 w-3" />
                </button>
              </span>
            ))}
            {uploadingCount > 0 ? (
              <span className="inline-flex items-center gap-1.5 rounded-full border border-white/15 bg-black/30 px-2.5 py-1 text-[11px] text-white/50">
                <Spinner className="h-3 w-3" /> uploading {uploadingCount} file{uploadingCount > 1 ? 's' : ''}…
              </span>
            ) : null}
          </div>
        ) : null}

        <div className="border-t border-[rgba(212,175,55,0.1)] p-4">
          <div className={cn('mx-auto max-w-3xl rounded-xl transition-colors', dragOver && 'bg-[rgba(212,175,55,0.06)] outline-1 outline-dashed outline-[rgba(212,175,55,0.4)]')}>
            <div className="mb-2 flex items-center gap-2">
              <button
                onClick={() => fileInputRef.current?.click()}
                disabled={uploadingCount > 0 || files.length >= MAX_FILES}
                className="inline-flex items-center gap-1.5 rounded-lg border border-[rgba(212,175,55,0.25)] px-2.5 py-1.5 text-[11px] text-white/55 transition-colors hover:bg-white/5 hover:text-white/80 disabled:opacity-50"
                title={`Attach files — up to ${MAX_FILES}. ${CAPABILITY_HINT}.`}
              >
                <Paperclip className="h-3.5 w-3.5" />
                Attach files
              </button>
              <input
                ref={fileInputRef}
                type="file"
                multiple
                className="hidden"
                onChange={(e) => {
                  if (e.target.files?.length) void uploadFiles(e.target.files)
                  if (fileInputRef.current) fileInputRef.current.value = ''
                }}
              />
              <span className="text-[10px] text-white/30">or drop files here</span>
            </div>

            <div className="flex items-end gap-2">
              <Textarea
                value={input}
                onChange={(e) => setInput(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); void send() }
                }}
                placeholder="Message RIISHE… (Enter to send, Shift+Enter for a new line)"
                rows={Math.min(4, Math.max(1, input.split('\n').length))}
                maxLength={12000}
                disabled={streaming}
                className="max-h-40 min-h-[46px] resize-none bg-black/30"
                aria-label="Message RIISHE"
              />
              {streaming ? (
                <Button onClick={stopGeneration} className="h-[46px] bg-[rgba(212,175,55,0.15)] px-4 text-[#f0c75e] hover:bg-[rgba(212,175,55,0.25)]" variant="outline" aria-label="Stop generating">
                  <Square className="h-4 w-4" />
                </Button>
              ) : (
                <Button onClick={() => void send()} disabled={!input.trim()} className="h-[46px] bg-[#d4af37] px-4 text-black hover:bg-[#e6c25a]" aria-label="Send message">
                  <Send className="h-4 w-4" />
                </Button>
              )}
            </div>
          </div>
        </div>
      </div>
    </div>
  )
}

/**
 * One assistant response: clean prose (citation markers render as source-name
 * links; unresolved ones are stripped), the honest verification note when one
 * exists, and CONSISTENT actions — Copy response, Regenerate, and View
 * sources (only when sources exist) — on EVERY response, not just the last.
 */
function AssistantBubble({
  msg,
  onRegenerate,
  streaming,
  renderers,
  researching,
  runningTool,
}: {
  msg: Msg
  onRegenerate: () => void
  streaming: boolean
  renderers: Parameters<typeof Markdown>[0]['components']
  researching: boolean
  runningTool: string | null
}) {
  const [sourcesOpen, setSourcesOpen] = useState(false)
  const hasSources = (msg.meta?.sources?.length ?? 0) > 0
  if (!msg.content) {
    // Empty draft: the live status line (search / tools / thinking).
    return researching ? (
      <span className="inline-flex items-center gap-2 text-xs text-white/50">
        <Globe className="h-3.5 w-3.5 animate-pulse text-[#d4af37]" /> Searching the web…
      </span>
    ) : runningTool ? (
      <span className="inline-flex items-center gap-2 text-xs text-white/50">
        <Terminal className="h-3.5 w-3.5 animate-pulse text-[#d4af37]" />
        {runningTool === 'working' ? 'Working…' : 'Running tools…'}
      </span>
    ) : (
      <span className="inline-flex items-center gap-2 text-xs text-white/40">
        <Spinner /> Thinking…
      </span>
    )
  }
  const claims = mapSourceClaims(msg.content, msg.meta?.sources ?? [])
  return (
    <>
      <Markdown
        content={linkifyCitations(msg.content, msg.meta?.sources)}
        components={renderers}
      />
      {msg.pending ? <Spinner className="ml-1 mt-1" /> : null}
      {msg.partial ? (
        <div className="mt-2 inline-flex items-center gap-1.5 rounded border border-amber-500/30 bg-amber-500/10 px-2 py-0.5 text-[10px] text-amber-300">
          <AlertTriangle className="h-3 w-3" /> Incomplete — the stream was stopped or ended early
        </div>
      ) : null}
      <AnswerMeta meta={msg.meta} forceOpen={sourcesOpen} claims={claims} />
      {!msg.pending ? (
        <div className="mt-2 flex flex-wrap items-center gap-2 border-t border-[rgba(212,175,55,0.12)] pt-2">
          <CopyMessageButton content={msg.content} />
          <button
            onClick={onRegenerate}
            disabled={streaming}
            className="inline-flex items-center gap-1 rounded px-1.5 py-0.5 text-[10px] text-white/45 transition-colors hover:bg-white/10 hover:text-white/80 disabled:opacity-40"
            aria-label="Regenerate response"
          >
            <RefreshCw className="h-3 w-3" /> Regenerate
          </button>
          {hasSources ? (
            <button
              onClick={() => setSourcesOpen(true)}
              className="inline-flex items-center gap-1 rounded px-1.5 py-0.5 text-[10px] text-white/45 transition-colors hover:bg-white/10 hover:text-white/80"
              aria-label="View sources"
              aria-expanded={sourcesOpen}
            >
              <ExternalLink className="h-3 w-3" /> View sources
            </button>
          ) : null}
        </div>
      ) : null}
    </>
  )
}

function CopyMessageButton({ content }: { content: string }) {
  const [copied, copy] = useCopy()
  return (
    <button
      onClick={() => copy(cleanAnswerForCopy(content))}
      className="inline-flex items-center gap-1 rounded px-1.5 py-0.5 text-[10px] text-white/45 transition-colors hover:bg-white/10 hover:text-white/80"
      aria-label="Copy response"
    >
      {copied ? <Check className="h-3 w-3 text-emerald-400" /> : <Copy className="h-3 w-3" />}
      {copied ? 'Copied' : 'Copy response'}
    </button>
  )
}

/**
 * Answer-first evidence: NO state badges, NO verification summary, NO tool
 * chips, NO "last checked" telemetry in the reading flow. What remains:
 *  - a short honest verification note ONLY when something material could not
 *    be confirmed (uncovered claims, stale sources, wrong-case retrieval,
 *    failed live verification);
 *  - a subtle collapsed "Sources" section listing what was really retrieved,
 *    each entry with its publisher, date, and the claim it supports.
 */
function AnswerMeta({
  meta,
  forceOpen,
  claims,
}: {
  meta?: MsgMeta
  forceOpen?: boolean
  claims: Map<number, string>
}) {
  const detailsRef = useRef<HTMLDetailsElement>(null)
  useEffect(() => {
    if (forceOpen && detailsRef.current) detailsRef.current.open = true
  }, [forceOpen])
  const sources = meta?.sources ?? []
  const note = meta?.verificationNote
  const researchFailed = meta?.states?.includes('TOOL_UNAVAILABLE') ?? false
  if (!researchFailed && !note && sources.length === 0) return null
  return (
    <div className="mt-2 border-t border-[rgba(212,175,55,0.12)] pt-2">
      {researchFailed ? (
        <div className="text-[11px] text-amber-300/90">
          Live sources could not be checked for this answer — treat current details as unverified.
        </div>
      ) : note ? (
        <div className="text-[11px] leading-snug text-white/40">{note}</div>
      ) : null}

      {sources.length > 0 ? (
        <details ref={detailsRef} className="group mt-1">
          <summary className="flex w-fit cursor-pointer list-none items-center gap-1 text-[11px] text-white/40 hover:text-white/65">
            <ChevronDown className="h-3 w-3 transition-transform group-open:rotate-180" />
            Sources ({sources.length})
          </summary>
          <ul className="mt-1.5 space-y-2 pl-4">
            {sources.map((s) => (
              <li key={s.id} id={`bean-src-${s.id}`} className="scroll-mt-6 break-words text-[11px] leading-snug">
                <a
                  href={s.url}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="break-words text-[#f0c75e] hover:underline"
                >
                  {s.title.slice(0, 90)}
                  <ExternalLink className="ml-1 inline h-2.5 w-2.5" />
                </a>
                <span className="text-white/35"> — {s.hostName.replace(/^www\./, '')}</span>
                {s.date ? (
                  <span className="ml-1 text-white/30" title="Publication date stated by the source — distinct from the event date">
                    · published {s.date}
                  </span>
                ) : (
                  <span className="ml-1 text-white/25" title="No publication date could be verified for this source">
                    · no date verified
                  </span>
                )}
                {s.social ? <span className="ml-1 text-amber-300/50">· social-media post (unverified provenance)</span> : null}
                <SourceClaimLine content={claims.get(s.id)} />
              </li>
            ))}
          </ul>
        </details>
      ) : null}
    </div>
  )
}

/** "Supports: …" line — the claim this source was cited for, when known. */
function SourceClaimLine({ content }: { content?: string }) {
  if (!content) return null
  return <div className="mt-0.5 text-[10.5px] leading-snug text-white/30">Supports: {content}</div>
}
