/**
 * BEAN Intelligence — RIISHE workspace (conversational AI).
 *
 * Answer-first reading experience: the response is clean natural prose; when
 * the server really retrieved evidence, sources stay behind a subtle
 * "Sources" toggle and inline citations render as concise clickable source
 * names (no numeric markers, no badges, no internal pipeline diagnostics).
 *
 * Capability is automatic — there are NO Auto/Web/Off or sandbox toggles in
 * the composer. The server's freshness policy retrieves when a question
 * needs current information, and the server-side tool policy executes code
 * only when a task genuinely needs it. Real orchestration events drive the
 * status line: "Searching the web…" appears only when search actually runs.
 *
 * A new conversation opens as the plain empty chat interface: no welcome
 * banner, no greeting card, no suggestion grid, no injected assistant
 * message. Greetings are generated by the model as part of the normal
 * conversation flow, like every other response.
 */
